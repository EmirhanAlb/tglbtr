export function detectLang() {
  try {
    const stored = localStorage.getItem("vertex.lang");
    if (stored === "tr" || stored === "en") return stored;
    const nav = (navigator.language || "en").toLowerCase();
    return nav.startsWith("tr") ? "tr" : "en";
  } catch (e) {
    return "en";
  }
}
